package ru.svoemesto.syp.admin.notify

/**
 * Типы уведомлений SYP.
 *
 * **Имя типа едет в потоке как имя события, а не как поле в общем потоке.**
 * Один поток на все типы означал бы, что обработчик вынужден разбирать поле
 * «а что это за сообщение» и что один неверно прочитанный тип молча уронил бы
 * чужой обработчик. Имя события разбирает сам поток: подписчик навешивается на
 * своё имя и не видит чужих сообщений вовсе.
 *
 * Имена — **свои, по домену**. Имена караокинской админки (`recordChange`,
 * `cacheQueueSize`) описывают чужой домен и у нас ничего не значат: у SYP нет
 * ни «записей» как сущности, ни кеша очереди разбора. Набор ниже выведен из
 * того, что оператор ждёт увидеть сам: ход работы, состояние очереди, итог
 * подсчёта суммы, готовность сценария и ошибку.
 *
 * @property wireName имя события в потоке SSE; оно же приходит клиенту в
 *   `addEventListener`
 * @see <a href="../../../../../../docs/features/first-vertical-slice.md">docs/features/first-vertical-slice.md</a>
 */
enum class SseEventType(
    val wireName: String,
) {
    /**
     * Ход задания: сколько единиц работы сделано из скольких.
     *
     * Отдельно от состояния: прогресс движется десятки раз за задание, а
     * состояние меняется пять раз за его жизнь. Смешивать их в одно событие
     * означало бы писать обработчик, который проверяет поле «а что пришло».
     */
    JOB_PROGRESS("jobProgress"),

    /**
     * Смена состояния задания: взято, начало работы, завершено, не удалось.
     *
     * Отдельное событие прогресса даёт то, чего прогресс не даёт вовсе:
     * сообщение о завершении. Последнее значение прогресса приходит на 99 %,
     * а без отдельного состояния экран остался бы «почти готов» навсегда.
     */
    JOB_STATE("jobState"),

    /**
     * Состояние очереди: сколько заданий работает, сколько ждёт, сколько
     * не удалось.
     *
     * Отдельное от задания: оператор смотрит на очередь целиком, а не на одно
     * задание, и «работает одно, ждут семь» — это другой вопрос, чем «сколько
     * кадров обработано».
     */
    QUEUE_STATE("queueState"),

    /**
     * Изменилось состояние суммы исходника серии.
     *
     * Подсчёт 5,6 ГБ идёт минутами, и без этого события экран суммы молчал бы
     * всё это время.
     */
    CHECKSUM_CHANGED("checksumChanged"),

    /**
     * Сценарий выдан, подписан и готов к выдаче пользователю.
     *
     * «Готов» означает ровно то, что сказано в контракте выдачи: файл записан
     * в состояние `READY`, подпись стоит. Незавершённый сценарий таким
     * событием не объявляется (ADR-0014).
     */
    RECIPE_READY("recipeReady"),

    /**
     * Отказ операции, которая не является заданием очереди.
     *
     * Отдельный тип нужен именно потому, что отказ не меняет состояние
     * задания: очередь о нём не знает и сообщить не может. Молчаливый отказ —
     * это экран, на котором ничего не происходит и непонятно почему.
     */
    ERROR("error"),
    ;

    companion object {
        /**
         * Находит тип по имени события в потоке.
         *
         * @param wireName имя события от клиента
         * @return тип либо `null`, если имя неизвестно: приходит оно из сети,
         *   и незнакомое имя — не повод ронять разбор потока
         */
        fun byWireName(wireName: String): SseEventType? = entries.firstOrNull { it.wireName == wireName }
    }
}
