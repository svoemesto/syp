package ru.svoemesto.syp.admin.characters

import ru.svoemesto.syp.core.media.RawFrame

/**
 * Заглушка детектора лиц.
 *
 * Заглушка существует, чтобы **граница задания `FACES` была законченной
 * вещью, а не заготовкой**: задание принимает поток кадров, передаёт их
 * детектору через интерфейс, проверяет каждое получение и код завершения
 * декодера — и всё это проверяется тестами, пока настоящего детектора нет.
 *
 * Настоящий детектор работает на видеокарте и требует среды исполнения,
 * которой на машине сейчас нет: карта есть, `onnxruntime`, `torch` и `nvcc`
 * не установлены. Это отдельная задача (T063), и она **не выполняется этим
 * кодом**.
 *
 * **Заглушка не выдаёт ни одного лица — и это её единственный результат.**
 * Пустой список здесь означает «детектора нет», а не «в кадре нет лиц»;
 * разница видна в [key] и в тексте итога задания. Заглушка, которая
 * возвращала бы выдуманные рамки, выглядела бы как готовый результат детекции
 * и была бы прямой подменой измерения.
 *
 * @see <a href="../../../../../../../../../docs/features/first-vertical-slice.md">docs/features/first-vertical-slice.md</a>
 */
class StubFaceDetector : FaceDetector {
    /** Идентификатор заглушки: в прогоне анализа виден как отсутствие детектора. */
    override val key: String = KEY

    /** Заглушка объявляет себя заглушкой: её пустой результат не читается как детекция. */
    override val isPlaceholder: Boolean = true

    /**
     * Не находит ничего: настоящего детектора в этой сборке нет.
     *
     * @param frame кадр; содержимое не читается
     * @return всегда пустой список
     */
    override fun detect(frame: RawFrame): List<DetectedFace> = emptyList()

    companion object {
        /**
         * Ключ заглушки.
         *
         * Строка содержит слово «заглушка» намеренно: прогон анализа, ключ
         * модели и текст отчёта показывают его оператору, и по нему видно,
         * что детекции не было.
         */
        const val KEY: String = "stub-face-detector-1"
    }
}
