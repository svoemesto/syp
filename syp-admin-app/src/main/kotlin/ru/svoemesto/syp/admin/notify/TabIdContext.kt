package ru.svoemesto.syp.admin.notify

/**
 * Идентификатор вкладки текущего запроса.
 *
 * Значение кладётся фильтром на входе запроса и **обязательно снимается в
 * `finally`**. Потоки контейнера переиспользуются: оставленное значение
 * «протечёт» в следующий несвязанный запрос, и подписка чужой вкладки
 * получила бы чужой идентификатор — либо, что хуже, чужое уведомление.
 *
 * Именно поэтому очистка вынесена и в [clear], и отдельно проверяется тестом:
 * забытый `remove()` — это не «мелочь», а тихая подмена принадлежности
 * события вкладке.
 *
 * @see <a href="../../../../../../docs/features/first-vertical-slice.md">docs/features/first-vertical-slice.md</a>
 */
object TabIdContext {
    private val current = ThreadLocal<TabId?>()

    /**
     * Кладёт идентификатор вкладки текущего запроса.
     *
     * @param tabId проверенный идентификатор вкладки
     */
    fun set(tabId: TabId) {
        current.set(tabId)
    }

    /**
     * Идентификатор вкладки текущего запроса.
     *
     * @return идентификатор либо `null`, если запрос шёл без него
     */
    fun get(): TabId? = current.get()

    /** Снимает значение. Вызывается в `finally` фильтра, всегда. */
    fun clear() {
        current.remove()
    }
}
