package ru.svoemesto.syp.admin.characters

import ru.svoemesto.syp.core.media.RawFrame

/**
 * Пять точек лица от детектора.
 *
 * Нужны эмбеддеру: модель распознавания учится на лицах, выровненных по этим
 * точкам, и без них вектор получается мусором. Порядок — левый глаз, правый глаз,
 * нос, левый и правый уголки рта; он один и в питоне, и здесь.
 *
 * @property eyeLeft левый глаз
 * @property eyeRight правый глаз
 * @property nose нос
 * @property mouthLeft левый угол рта
 * @property mouthRight правый угол рта
 */
data class FacePoints(
    val eyeLeft: IntPoint = IntPoint(),
    val eyeRight: IntPoint = IntPoint(),
    val nose: IntPoint = IntPoint(),
    val mouthLeft: IntPoint = IntPoint(),
    val mouthRight: IntPoint = IntPoint(),
)

/** Точка на кадре. */
data class IntPoint(
    val x: Int = 0,
    val y: Int = 0,
)

/**
 * Лицо, найденное в кадре.
 *
 * Значение описывает **рамку в координатах кадра полного разрешения**: и
 * номер кадра, и координаты — источник правды для дальнейших вычислений
 * (ADR-0001, FR-034). Уверенность детектора хранится вместе с рамкой, и по
 * ней потом отбираются эталоны для обучения.
 *
 * Пустой список результатов — допустимое значение: кадр без лиц обычен.
 * Непустой список обязан быть осмысленным, поэтому перевёрнутая рамка или
 * уверенность вне `0…1` отвергаются сразу, а не на записи в базу: испорченное
 * значение, дошедшее до базы, вернулось бы в интерфейс как рамка лица.
 *
 * @property x1 левая граница рамки в пикселях кадра
 * @property y1 верхняя граница рамки в пикселях кадра
 * @property x2 правая граница рамки в пикселях кадра
 * @property y2 нижняя граница рамки в пикселях кадра
 * @property confidence уверенность детектора, от 0 до 1
 * @see <a href="../../../../../../../../../docs/features/first-vertical-slice.md">docs/features/first-vertical-slice.md</a>
 */
data class DetectedFace(
    val x1: Int,
    val y1: Int,
    val x2: Int,
    val y2: Int,
    val confidence: Double,
    /** Пять точек лица: левый глаз, правый глаз, нос, уголки рта. */
    val points: FacePoints = FacePoints(),
) {
    init {
        require(x1 < x2 && y1 < y2) {
            "Рамка лица перевёрнута или пуста: ($x1, $y1) — ($x2, $y2)"
        }
        require(confidence in 0.0..1.0) {
            "Уверенность детектора вне диапазона 0…1: $confidence"
        }
    }

    /**
     * Проверяет, что рамка помещается в кадр.
     *
     * Проверка стоит на границе канала: рамка за пределами кадра означает,
     * что детектор работает с размерами, которых у кадра нет. Такое
     * отвергается с текстом, в котором назван детектор, — иначе дефект
     * всплыл бы позже, на чужом экране и под чужим именем.
     *
     * @param width ширина кадра
     * @param height высота кадра
     * @throws IllegalArgumentException если рамка выходит за пределы кадра
     */
    fun requireInside(
        width: Int,
        height: Int,
    ) {
        require(x1 >= 0 && y1 >= 0 && x2 <= width && y2 <= height) {
            "Рамка лица ($x1, $y1) — ($x2, $y2) выходит за пределы кадра ${width}x$height"
        }
    }
}

/**
 * Детектор лиц.
 *
 * Интерфейс — **граница задания `FACES`**: задание принимает поток кадров и
 * передаёт их детектору, а решение о том, как именно ищется лицо, остаётся
 * за реализацией. Реализация на видеокарте — задача T063; она же владеет
 * инициализацией среды исполнения, которой на этой машине нет.
 *
 * Что обязательно для любой реализации:
 *
 * 1. **кадр не сохраняется** ни в файл, ни в объектное хранилище, ни в
 *    очередь: на диск идут только превью (FR-024, ADR-0002);
 * 2. **вызов синхронный и на каждый кадр** — адаптивный шаг запрещён решением
 *    ADR-0002, и никакая реализация не вправе его ввести;
 * 3. **[key]** называет реализацию и попадает в прогон анализа: результат,
 *    полученный другим детектором, нельзя выдавать за этот.
 *
 * @see <a href="../../../../../../../../../docs/features/first-vertical-slice.md">docs/features/first-vertical-slice.md</a>
 */
interface FaceDetector {
    /** Идентификатор реализации детектора; попадает в прогон анализа. */
    val key: String

    /**
     * Является ли реализация заглушкой.
     *
     * Признак обязателен, а не украшение: реализация, которая ничего не
     * ищет, обязана объявить себя заглушкой, иначе её пустой результат
     * читался бы как вывод детектора — «в кадре нет лиц» вместо «детектора
     * нет». По признаку текст результата задания называет заглушку прямо.
     *
     * Настоящий детектор это значение не переопределяет.
     */
    val isPlaceholder: Boolean
        get() = false

    /**
     * Ищет лица в одном кадре.
     *
     * @param frame кадр полного разрешения; буфер переиспользуется, ссылку на
     *   него хранить нельзя
     * @return найденные лица; пустой список означает «в кадре нет лиц», если
     *   только реализация не объявила себя заглушкой
     */
    fun detect(frame: RawFrame): List<DetectedFace>
}
