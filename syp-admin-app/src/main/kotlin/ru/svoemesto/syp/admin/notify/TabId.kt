package ru.svoemesto.syp.admin.notify

import java.security.SecureRandom
import java.util.Locale

/**
 * Идентификатор вкладки браузера.
 *
 * Идентификатор **приходит от клиента** и потому недоверенное значение: он
 * целиком лежит в адресе подписки, то есть написан вручную чем угодно — от
 * чужого скрипта до опечатки. Поэтому он проверяется по форме, и значение,
 * форму не прошедшее, **не используется**: подставляется серверный.
 *
 * Что идентификатор вкладки **не** решает: он не является ни идентификатором
 * пользователя, ни признаком доверия, ни ключом доступа к данным. В первом
 * срезе аутентификации нет вовсе, стек локальный, и подписка отдаёт ровно те
 * же данные, что и обычный чтение очереди. Проверка формы — это защита от
 * мусора в реестре подключений, а не механизм безопасности; выдавать
 * идентификатор вкладки средством обхода чего-либо было бы выдумкой.
 *
 * Идентификатор нужен, чтобы **различать вкладки**: один и тот же браузер с
 * двумя открытыми экранами — это две подписки, и закрытие одной не должно
 * гасить вторую.
 *
 * @property value проверенное значение идентификатора
 * @see <a href="../../../../../../docs/features/first-vertical-slice.md">docs/features/first-vertical-slice.md</a>
 */
@JvmInline
value class TabId(
    val value: String,
) {
    companion object {
        /** Имя параметра адреса, в котором приходит идентификатор вкладки. */
        const val PARAMETER: String = "tabId"

        /** Минимальная длина идентификатора вкладки. */
        const val MIN_LENGTH: Int = 8

        /** Максимальная длина идентификатора вкладки. */
        const val MAX_LENGTH: Int = 64

        /** Разрядность серверного идентификатора в шестнадцатеричной записи. */
        private const val SERVER_ID_BYTES: Int = 16

        private val random = SecureRandom()

        /**
         * Допустимая форма: латинские буквы, цифры, дефис и подчёркивание.
         *
         * Набор сознательно узкий: идентификатор попадает в ключ реестра
         * подключений и в текст журнала записи, и любое значение из этих трёх
         * групп символов читаемо и безопасно для того и другого.
         */
        private val FORM: Regex = Regex("^[A-Za-z0-9_-]+$")

        /**
         * Проверяет значение, пришедшее от клиента.
         *
         * @param raw значение из адреса; может быть отсутствующим или пустым
         * @return `true`, если значение можно использовать как ключ подписки
         */
        fun isAcceptable(raw: String?): Boolean =
            raw != null &&
                raw.length in MIN_LENGTH..MAX_LENGTH &&
                FORM.matches(raw)

        /**
         * Проверяет значение от клиента либо подставляет серверное.
         *
         * Подстановка, а не отказ: негодный идентификатор вкладки не делает
         * подписку бессмысленной — он лишь не годится в ключ. Отказ здесь
         * показался бы оператору «сервер не принимает подписку» из-за
         * опечатки в ссылке, тогда как работать можно.
         *
         * @param raw значение из адреса
         * @return проверенный идентификатор либо серверный, если присланный
         *   не годится
         */
        fun of(raw: String?): TabId = if (isAcceptable(raw)) TabId(raw!!) else TabId(generate())

        /**
         * Создаёт идентификатор на стороне сервера.
         *
         * @return 32 шестнадцатеричных символа
         */
        fun generate(): String {
            val bytes = ByteArray(SERVER_ID_BYTES)
            random.nextBytes(bytes)
            return bytes.joinToString("") { byte ->
                "%02x".format(Locale.ROOT, byte)
            }
        }
    }
}
