package ru.svoemesto.syp.core.jobs

/**
 * Снимок того, что изменилось в задании.
 *
 * Это не задание целиком и не представление строки базы: только те четыре
 * величины, по которым интерфейсу становится ясно, что работа идёт, что она
 * закончилась или что она не удалась.
 *
 * Снимок собирается **внутри** той же транзакции, которая изменила задание, и
 * передаётся подписчику уже после фиксации транзакции. Значит, подписчик не
 * может увидеть изменение, которого в базе нет, и не обязан перечитывать
 * задание, чтобы узнать, что с ним произошло.
 *
 * @property id идентификатор задания
 * @property kind вид задания
 * @property state состояние после изменения
 * @property subject предмет работы: серия или версия модели либо `null`
 * @property progress прогресс на момент изменения
 * @property errorText текст ошибки при состоянии [JobState.ERROR], иначе `null`
 * @see <a href="../../../../../docs/features/first-vertical-slice.md">docs/features/first-vertical-slice.md</a>
 */
data class JobSignal(
    val id: Long,
    val kind: JobKind,
    val state: JobState,
    val subject: JobSubject,
    val progress: JobProgress,
    val errorText: String?,
)

/**
 * Наблюдатель изменений очереди заданий.
 *
 * Существует по одной причине: **ход задания должен быть виден без опроса**.
 * Пока единственный способ узнать, что задание дошло до конца, — повторно
 * спросить сервер, оператор смотрит на устаревший экран и не понимает, идёт
 * ли работа.
 *
 * Модуль не знает, кто подписан: [JobQueueListener.NONE] — заглушка, и весь
 * набор уведомлений живёт в бэкендах. Обратная связь тоже запрещена: подписчик
 * не может изменить состояние задания из обработчика, иначе переход состояний
 * пошёл бы в обход проверки разрешённости.
 *
 * Обработчик, бросивший исключение, **не ломает работу**: очередь уже
 * записана, а потеря уведомления — это молчащий экран, а не неверные данные.
 *
 * @see <a href="../../../../../docs/features/first-vertical-slice.md">docs/features/first-vertical-slice.md</a>
 */
interface JobQueueListener {
    /**
     * Состояние задания изменилось: его взяли, оно начало работу, закончилось
     * или не удалось.
     *
     * @param signal снимок изменения
     */
    fun onStateChanged(signal: JobSignal) {
        // По умолчанию никто не слушает: очередь работает и без уведомлений.
    }

    /**
     * Прогресс задания изменился.
     *
     * @param signal снимок изменения; состояние в нём — то, в котором задание
     *   находится сейчас
     */
    fun onProgressChanged(signal: JobSignal) {
        // По умолчанию никто не слушает.
    }

    companion object {
        /** Подписчик, который ничего не делает. */
        val NONE: JobQueueListener =
            object : JobQueueListener {
                override fun toString(): String = "JobQueueListener.NONE"
            }
    }
}
