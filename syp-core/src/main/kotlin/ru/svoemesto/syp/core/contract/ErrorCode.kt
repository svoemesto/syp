package ru.svoemesto.syp.core.contract

/**
 * Машинные коды ошибок, общие для обоих бэкендов.
 *
 * Код ошибки — часть контракта: по нему интерфейс принимает решение, а
 * человек читает сообщение. Поэтому код один и тот же в админке и в публичной
 * части, а сообщение — всегда на русском (constitution I).
 *
 * Код не меняется после выдачи: переименование кода ломает клиента так же,
 * как переименование столбца в базе. Нужна новая пара «код, сообщение», а не
 * правка старой.
 *
 * @property httpStatus код ответа HTTP, который соответствует ошибке
 * @property message текст ошибки для человека
 * @see <a href="../../../../../docs/features/first-vertical-slice.md">docs/features/first-vertical-slice.md</a>
 */
enum class ErrorCode(
    val httpStatus: Int,
    val message: String,
) {
    /** Запрос не понят: нет обязательного поля или значение не того типа. */
    BAD_REQUEST(400, "Запрос не понят"),

    /** Источник серии недоступен: файла нет или он не читается. */
    SOURCE_UNREADABLE(400, "Исходный файл серии недоступен"),

    /** Путь серии лежит вне корня каталога сериала. */
    PATH_OUTSIDE_SERIAL_ROOT(400, "Путь серии лежит вне корня каталога сериала"),

    /** Авторизация не требуется: ошибка аутентификации в срезе не бывает. */
    NOT_FOUND(404, "Объект не найден"),

    /** Действие конфликтует с состоянием объекта. */
    CONFLICT(409, "Действие конфликтует с состоянием объекта"),

    /** Нарушено ограничение целостности, заданное базой. */
    CONSTRAINT_VIOLATED(409, "Нарушено ограничение целостности"),

    /** Серии сборки несовместимы: различаются параметры файла. */
    SERIES_INCOMPATIBLE(409, "Серии сборки несовместимы между собой"),

    /**
     * У серии нет актуальной суммы исходника.
     *
     * Имя приведено к контракту
     * [`public-api.md`](../../../../../../specs/001-first-vertical-slice/contracts/public-api.md)
     * и [`admin-api.md`](../../../../../../specs/001-first-vertical-slice/contracts/admin-api.md):
     * оба называют этот отказ `CHECKSUM_NOT_READY`. Код в перечислении ещё не
     * выдавался ни одному клиенту, поэтому приведение названия к контракту
     * ничего не ломает, а расхождение названий убрано.
     */
    CHECKSUM_NOT_READY(409, "У серии нет актуальной суммы исходника: поставьте пересчёт и дождитесь его окончания"),

    /** Внешняя программа завершилась с ненулевым кодом. */
    EXTERNAL_PROGRAM_FAILED(500, "Внешняя программа завершилась с ошибкой"),

    /** Внутренняя ошибка сервера. */
    INTERNAL_ERROR(500, "Внутренняя ошибка сервера"),

    /** Ответственность лежит не на том приложении. */
    NOT_IMPLEMENTED_IN_THIS_BACKEND(501, "Операция не входит в ответственность этого приложения"),
    ;

    companion object {
        /**
         * Находит код по имени.
         *
         * @param name имя кода
         * @return код или `null`, если такого кода нет
         */
        fun byName(name: String): ErrorCode? = entries.firstOrNull { it.name == name }
    }
}
