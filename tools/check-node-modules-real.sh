#!/usr/bin/env bash
#
# check-node-modules-real.sh — каталог зависимостей фронтенда настоящий.
#
# Зачем: однажды каталог `node_modules` оказался символической ссылкой на
# самого себя. Каталог есть, путь есть, а зависимостей нет. Сборка при этом
# падала не с «зависимости не установлены», а с молчаливым обрывом на
# `vue-tsc --noEmit`, и выглядела как успех: образ не создавался, а в логе
# была последняя строка запуска.
#
# Что проверяем: у каждого фронтенда `node_modules` обязан быть каталогом, а
# не ссылкой, и содержать хотя бы одну зависимость.
#
# Проверка проходит на чистом дереве после установки и падает на дереве,
# где каталог заменён ссылкой.

set -uo pipefail

# В рабочей копии субагента каталога зависимостей нет намеренно: он
# ставится при сборке образа, и проверять его здесь нечего. Основное
# дерево проверяется по-настоящему — ради него проверка и написана.
# Признак копии — служебный каталог git внутри .git.
if git rev-parse --git-dir 2>/dev/null | grep -q "/worktrees/"; then
    printf 'ОК: рабочая копия, каталоги зависимостей не проверяются\n'
    exit 0
fi

readonly FRONTENDS=("syp-admin-web" "syp-public-web")

failed=0

report_fail() {
    printf '  %-4s СБОЙ  %s\n' "ОШ" "$1"
    failed=$((failed + 1))
}

report_ok() {
    printf '  %-4s ок    %s\n' "ок" "$1"
}

printf '%s\n' "=== SYP: каталог зависимостей фронтенда настоящий =="

for frontend in "${FRONTENDS[@]}"; do
    modules="${frontend}/node_modules"

    # Порядок проверок важен: сначала «это ссылка», и только потом «существует
    # ли что-то по ссылке». Ссылка на саму себя не существует как объект, и
    # при обратном порядке проходит как «зависимости не установлены» — то есть
    # ровно тот случай, из-за которого сборка молча обрывается.
    # Отсутствие каталога — тоже нарушение, а не «не установлено, и так
    # сойдёт». Сборка образа идёт по слоям и полагается, что зависимости уже
    # на месте; каталога нет — образ не создаётся, а лог обрывается на
    # молчаливой точке и выглядит как успех. Проверка обязана говорить «нельзя»
    # там, где работать нельзя.
    if [[ ! -L "${modules}" && ! -e "${modules}" ]]; then
        report_fail "${frontend}/node_modules отсутствует: поставьте зависимости (cd ${frontend} && npm install)"
        continue
    fi

    if [[ -L "${modules}" ]]; then
        # Ссылка сама по себе законна: рабочая копия субагента указывает на
        # каталог основного дерева, и зависимости там настоящие. Запрещено
        # другое — ссылка, за которой ничего нет.
        target="$(readlink -f "${modules}" 2>/dev/null || true)"
        if [[ -z "${target}" || "${target}" == "${modules}" ]]; then
            report_fail "${frontend}/node_modules — ссылка на сам себя, зависимостей нет"
            continue
        fi
        if [[ ! -d "${target}" ]]; then
            report_fail "${frontend}/node_modules — ссылка на ${target}, а такого каталога нет"
            continue
        fi
        # `-L` обязателен: без него просмотр не заходит по ссылке, и каталог
        # за ней выглядит пустым даже когда в нём есть зависимости — а каталог
        # со ссылкой на самого себя выглядит непустым.
        behind="$(find -L "${target}" -mindepth 1 -maxdepth 1 2>/dev/null | wc -l | tr -d ' ')"
        if [[ "${behind}" -eq 0 ]]; then
            report_fail "${frontend}/node_modules — ссылка на пустой каталог ${target}"
            continue
        fi
        report_ok "${frontend}: ссылка на настоящий каталог, записей за ним ${behind}"
        continue
    fi

    if [[ ! -d "${modules}" ]]; then
        report_fail "${modules} существует, но это не каталог"
        continue
    fi

    count="$(find "${modules}" -mindepth 1 -maxdepth 1 2>/dev/null | wc -l | tr -d ' ')"
    if [[ "${count}" -eq 0 ]]; then
        report_fail "${modules} пуст: каталог есть, а зависимостей нет"
        continue
    fi

    report_ok "${frontend}: каталог настоящий, записей ${count}"
done

if [[ "${failed}" -gt 0 ]]; then
    printf '%s\n' "ЗАМЕЧАНИЙ: ${failed}. Сборка образа молча на этом обрывается."
    exit 1
fi

printf '%s\n' "ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ"
