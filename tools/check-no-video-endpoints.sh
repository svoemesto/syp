#!/usr/bin/env bash
# SYP — guard FR-085 и FR-088: у публичного бэкенда нет видео и разметки.
#
# Публичная часть отдаёт сценарий сборки и открытый ключ проверки. Видеофайлов
# на ней нет ни в каком виде: ни отдачи, ни приёма, ни хранения (ADR-0009,
# FR-088). Это не запрет в договорённостях, а отсутствие: аутентификации в
# первый срез нет, поэтому «нет в публичной части» обеспечивается **отсутствием
# эндпоинта** — эндпоинта, которого нет, вызвать нельзя.
#
# Сценарий в публичной части не создаётся и не подписывается: выдачу и подпись
# выполняет админский бэкенд, где живёт закрытый ключ (ADR-0014, решение
# владельца 2026-10-03). Публичная часть только читает уже подписанное.
#
# Скрипт падает, если в публичном бэкенде появится:
#   - эндпоинт, отдающий или принимающий видеофайл;
#   - эндпоинт разметки, обучения или настроек;
#   - исполнитель заданий;
#   - эндпоинт, создающий или изменяющий сценарий сборки.
#
# Использование:
#   bash tools/check-no-video-endpoints.sh            проверить syp-public-app
#   bash tools/check-no-video-endpoints.sh <каталог>  проверить указанный каталог
#
# Код возврата: 0 — нарушений нет, 1 — нарушения найдены.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}" || exit 1

errors=0

# Комментарии вырезаются перед разбором: они объясняют, чего быть не должно, и
# упоминание запрещённого слова в объяснении нарушением не является.
#
# Фильтр вставлен прямо в конвейер, а не назван функцией: `xargs` запускает
# программы, а не функции оболочки, и объявленная функция молча превращалась бы
# в «нет такого файла» — проверка проходила бы, ничего не прочитав.
STRIP='s{/\*(?:[^*]|\*(?!/))\*/}{}gs; s{//[^\n]*}{}g'

report() {
    printf 'НАРУШЕНИЕ FR-085/FR-088 в %s: %s\n' "$1" "$2" >&2
    errors=$((errors + 1))
}

check_public_module() {
    local dir="$1"
    local sources
    sources="${dir}/src/main"
    if [[ ! -d "${sources}" ]]; then
        report "${dir}" "каталог исходников ${sources} не найден"
        return
    fi

    # Видео и хранилище: сценарий сборки — текст, а не видеофайл. Исключение
    # `RECIPE` в перечислении видов артефактов — общий код, а не видео.
    if find "${sources}" -name '*.kt' -print0 | xargs -0 -r perl -0pe "${STRIP}" \
       | grep -nEi 'MultipartFile|produces *= *"video/|consumes *= *"video/|\.mp4|\.mkv|\.avi|\.mov|video/mp4|video/x-matroska'; then
        report "${dir}" "публичный бэкенд не должен отдавать и принимать видеофайлы (FR-088, ADR-0009)"
    fi

    # Разметка, обучение и настройки: ответственность админки. Публичная часть
    # применяет фильтр и выбирает сцены, но не доводит границы и не обучает.
    if find "${sources}" -name '*.kt' -print0 | xargs -0 -r perl -0pe "${STRIP}" \
       | grep -nE '@(Post|Put|Patch|Delete)Mapping' | grep -iE 'scene|shot|frame|boundary|train|model|setting|person' \
       | grep -v 'recipes'; then
        report "${dir}" "публичный бэкенд не должен содержать эндпоинты разметки, обучения или настроек (FR-085)"
    fi

    # Исполнитель заданий: у публичного бэкенда его нет вовсе.
    if find "${sources}" -name '*.kt' -print0 | xargs -0 -r perl -0pe "${STRIP}" \
       | grep -nE 'class .*(JobWorker|Worker)|@Scheduled|ExecutorService'; then
        report "${dir}" "у публичного бэкенда не должно быть исполнителя заданий (FR-085)"
    fi

    # Закрытый ключ подписи: он живёт только в контейнере админки. Отдать его
    # рядом с тем, кто проверяет подпись, — значит перестать отличать «свой»
    # сценарий от «чужого» (ADR-0011).
    if find "${sources}" -name '*.kt' -print0 | xargs -0 -r perl -0pe "${STRIP}" \
       | grep -nE 'SYP_SIGNING_PRIVATE_KEY|ENV_SIGNING_PRIVATE_KEY|privateKeyFromBase64'; then
        report "${dir}" "закрытый ключ подписи не должен попадать в публичный бэкенд (ADR-0011)"
    fi

    # Выдача сценария: её выполняет админский бэкенд, где живёт закрытый ключ
    # подписи. Эндпоинта, создающего сценарий, у публичного бэкенда не
    # существует; чтение выданного — есть, и guard на него не смотрит
    # (ADR-0014).
    if find "${sources}" -name '*.kt' -print0 | xargs -0 -r perl -0pe "${STRIP}" \
       | grep -nE '@(Post|Put|Patch|Delete)Mapping\([^)]*"/api/recipes'; then
        report "${dir}" "эндпоинт создания сценария не должен попадать в публичный бэкенд (ADR-0014)"
    fi
}

if [[ $# -gt 0 ]]; then
    for argument in "$@"; do
        check_public_module "${argument}"
    done
else
    check_public_module "syp-public-app"
fi

if [[ ${errors} -ne 0 ]]; then
    printf 'ПРОВАЛЕНО: нарушений ответственности публичной части — %d\n' "${errors}" >&2
    exit 1
fi
printf 'OK: у публичного бэкенда нет видео, разметки, обучения, исполнителя заданий и выдачи сценария (FR-085, FR-088, ADR-0014)\n'
exit 0
