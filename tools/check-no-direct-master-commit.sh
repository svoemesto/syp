#!/usr/bin/env bash
# Проверяет, что коммит делается не прямо в master.
#
# Правило «только feature-ветка и слияние» и так есть в трёх местах: защита
# ветки на GitHub, pre-commit и CI. Но за сессию оно нарушалось шесть раз, и
# причина вся одна: после слияния основное дерево остаётся на master, следующий
# коммит уходит туда же, и всё, что думали, сделано, лежит в master мимо ревью.
#
# Защита ветки на GitHub такой коммит отвергает — но только при отправке, когда
# правка уже сделана, и это дороже, чем отказ в момент коммита. Поэтому проверка
# стоит здесь: узнать об этом дешевле всего на строке «git commit».
set -euo pipefail

branch=$(git branch --show-current 2>/dev/null || true)

if [ "${branch}" != "master" ]; then
    exit 0
fi

# Коммит в master запрещён. На ревью ветка называется иначе, поэтому исключение
# невозможно: иначе проверку можно было бы обойти, назвав ветку «master».
cat >&2 <<'ПРЕДУПРЕЖДЕНИЕ'
ПРАВИЛО: коммит прямо в master запрещён.

Номер ветки берётся скриптом, ветка создаётся от master, работа идёт в ней:

    N=$(./tools/reserve-branch-number.sh <slug>)
    git branch "${N}-<slug>" origin/master
    git switch "${N}-<slug>"
    # ... работа ...
    git commit && git push -u origin "${N}-<slug>"
    gh pr create --base master --head "${N}-<slug>"

Причина запрета: в master шесть раз уходил коммит, которого не видел ни один
ревью. GitHub такой коммит отвергает, но узнать об этом на строке «git commit»
дешевле, чем после того, как работа уже сделана.
ПРЕДУПРЕЖДЕНИЕ

exit 1
