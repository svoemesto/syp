#!/usr/bin/env bash
#
# check-ready-to-work.sh — состояние проекта, в котором можно начинать порцию.
#
# Зачем: за сессию подготовка рабочей копии обрывалась семь раз, и всякий
# раз уже после того, как номер потрачен. Причина одна и та же: основное
# дерево оказывалось не на master, а сообщение git указывало на основное
# дерево — то есть на то, что как раз и было сломано. Читается как «не
# повезло», и порция начинается заново.
#
# Что проверяем до начала работы, а не после:
#   1. основное дерево на master — иначе рабочую копию не создать;
#   2. нет рабочих копий без каталога (запись есть, каталога нет);
#   3. нет каталогов рабочих копий без записи (каталог есть, записи нет) —
#      именно это состояние ломало добавление новой копии.
#
# Проверка ничего не меняет: она только говорит, можно ли начинать.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}" || exit 1

failed=0

report_fail() {
    printf '  %-4s СБОЙ  %s\n' "ОШ" "$1"
    failed=$((failed + 1))
}

report_ok() {
    printf '  %-4s ок    %s\n' "ок" "$1"
}

printf '%s\n' "=== SYP: состояние, в котором можно начинать порцию ==="

# Требование «на master» относится только к основному дереву: рабочая копия
# субагента обязана быть на своей ветке, и требование к ней неприменимо.
# Основным считается дерево, внутри которого лежит каталог `.git`, а не
# файл-указатель на него.
if [[ -d ".git" ]]; then
    head_ref="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo неизвестно)"
    if [[ "${head_ref}" == "master" ]]; then
        report_ok "основное дерево на master"
    else
        report_fail "основное дерево на ветке ${head_ref} — верните: git switch master"
    fi
else
    report_ok "рабочая копия: $(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo неизвестно)"
fi

# Записи о рабочих копиях без каталога: git считает ветку занятой той копией,
# которой уже нет, и отказывает в добавлении новой.
orphaned=0
while IFS= read -r name; do
    [[ -z "${name}" ]] && continue
    [[ ! -d ".worktrees/${name}" ]] && orphaned=$((orphaned + 1))
done < <(ls -1 .git/worktrees 2>/dev/null || true)

if [[ "${orphaned}" -eq 0 ]]; then
    report_ok "записи о рабочих копиях целы"
else
    report_fail "записей о рабочих копиях без каталога: ${orphaned} — почините: git worktree prune"
fi

# Каталоги без записи: добавление новой копии отказывает на уже занятом пути,
# и сообщение об этом указывает на основное дерево.
unregistered=0
while IFS= read -r dir; do
    [[ -z "${dir}" ]] && continue
    name="$(basename "${dir}")"
    [[ ! -d ".git/worktrees/${name}" ]] && unregistered=$((unregistered + 1))
done < <(find .worktrees -mindepth 1 -maxdepth 1 -type d 2>/dev/null || true)

if [[ "${unregistered}" -eq 0 ]]; then
    report_ok "каталоги рабочих копий зарегистрированы"
else
    report_fail "каталогов рабочих копий без записи: ${unregistered} — удалите их или повторите добавление"
fi

if [[ "${failed}" -gt 0 ]]; then
    printf '%s\n' "НАЧИНАЬ НЕЛЬЗЯ: сначала верните состояние, иначе порция оборвётся на первом же шаге."
    exit 1
fi

printf '%s\n' "МОЖНО НАЧИНАТЬ"
