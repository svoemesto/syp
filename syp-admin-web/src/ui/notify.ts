// Уведомления о действиях, которые уходят в очередь заданий.
//
// Отдельный файл, а не состояние внутри экрана, потому что сообщение одно и то
// же из разных мест: поставил анализ, поставил пересчёт — и оператор должен
// увидеть подтверждение независимо от того, какой экран открыт. Раньше кнопки
// постановки просто ничего не показывали, и оператор нажимал их повторно.
//
// Показ идёт через `useToast` из `bootstrap-vue-next` — тем же набором, что и в
// админке Karaoke (ADR-0015). Компонент `BApp` в корне устанавливает
// оркестратор тостов, поэтому вручную контейнер в разметку не кладётся.

import { useToast } from 'bootstrap-vue-next'

/**
 * Тон уведомления: соответствует смыслу, а не оформлению Bootstrap.
 *
 * `danger` добавлен ради отказов: ошибка задания и отказ выдачи сценария
 * приходят по подписке и должны выглядеть отказом, а не «заданием поставлено».
 */
export type NoticeTone = 'success' | 'info' | 'warning' | 'danger'

/** Сколько миллисекунд показывается сообщение. */
const LIFETIME_MS = 6000

/** Заголовок сообщения по тону. */
const TITLES: Record<NoticeTone, string> = {
  success: 'Готово',
  info: 'Задание поставлено',
  warning: 'Внимание',
  danger: 'Отказ',
}

/**
 * Компоновщик уведомлений для экрана.
 *
 * Вызывается из `setup`, потому что `useToast` берёт контроллер из контекста
 * компонента, а не из глобального состояния.
 *
 * @returns функция показа сообщения
 */
export function useNotify(): (text: string, tone?: NoticeTone) => void {
  const toast = useToast()

  /**
   * Показывает сообщение и убирает его сама через несколько секунд.
   *
   * @param text текст для оператора
   * @param tone тон сообщения
   */
  return function notify(text: string, tone: NoticeTone = 'success'): void {
    void toast.show({
      title: TITLES[tone],
      body: text,
      variant: tone,
      interval: LIFETIME_MS,
    })
  }
}
