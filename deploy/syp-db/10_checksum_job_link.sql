-- 10_checksum_job_link.sql — SYP, PostgreSQL 16
--
-- Связь записи справочника сумм с заданием, которое её считало.
-- Спецификация: FR-003, FR-089, FR-092.
-- Модель: specs/001-first-vertical-slice/data-model.md, раздел 2.19.
-- Миграция добавочная, применяется один раз после 09_series_keyframe_bitmap.sql.
-- Применённые миграции не переписываются (constitution III).
--
-- Зачем связь. Запись справочника сумм живёт дольше задания: она и есть
-- результат. Но без ссылки на задание запись, оставшаяся в состоянии
-- CREATING или WORKING после прерванного подсчёта, не скажет ни слова о
-- причине — а по FR-092 у ошибки должен быть текст, и текст ошибки задания
-- известен только заданию. Кроме того, по ссылке видно, какое задание
-- считало сумму: при отладке пересчётов это первое, что спрашивают.
--
-- Ссылка внешняя и обнуляемая: удаление задания не должен удалять результат
-- (иначе терялась бы история пересчётов), поэтому ON DELETE SET NULL.

ALTER TABLE source_file_checksum
    ADD COLUMN IF NOT EXISTS job_id BIGINT;

ALTER TABLE source_file_checksum
    ADD CONSTRAINT source_file_checksum_job_fk
        FOREIGN KEY (job_id) REFERENCES job (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS source_file_checksum_job_idx
    ON source_file_checksum (job_id) WHERE job_id IS NOT NULL;

COMMENT ON COLUMN source_file_checksum.job_id IS
    'Задание HASH, которое считало эту сумму. Обнуляется при удалении задания:
     результат переживает задание, а не наоборот (FR-003, FR-092).';

-- ---------------------------------------------------------------------------
-- Суммы у незавершённого подсчёта не существует.
--
-- Запись справочника появляется в момент постановки задания, а не после
-- подсчёта: иначе прерванный подсчёт оставил бы после себя пустоту, и по
-- записям нельзя было бы отличить «считается» от «никогда не считалось»
-- (FR-003). Признак обязательности столбца снимается, а действующее
-- ограничение формата при этом начинает пропускать отсутствие значения:
-- в SQL результат сравнения с NULL есть NULL, а проверка ограничения
-- отклоняет только явный FALSE.
--
-- Формат значения при этом не ослабляется: готовая сумма обязана быть ровно
-- из 64 шестнадцатеричных символов в нижнем регистре — иначе её не примет
-- `sha256sum` на машине пользователя без преобразований.
-- ---------------------------------------------------------------------------

ALTER TABLE source_file_checksum
    ALTER COLUMN digest DROP NOT NULL;

COMMENT ON COLUMN source_file_checksum.digest IS
    'Сумма sha256: 64 шестнадцатеричных символа в нижнем регистре. При незавершённом подсчёте значения нет: запись создаётся при постановке задания, а сумма появляется после чтения файла (FR-003).';
