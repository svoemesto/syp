-- Сезон серии.
--
-- Сериал — это произведение: у «Игры престолов» десятки серий в нескольких
-- сезонах, у фильма — одна серия или несколько, и сезона у них нет. Поэтому
-- поле необязательное: пустое значение означает «сезон не задан», а не
-- «сезон забыли внести».
--
-- Порядковый номер серии при этом остаётся сквозным по всему сериалу: он
-- задаёт последовательность, по которой сценарий собирает серию в целом.
ALTER TABLE series ADD COLUMN season integer NULL;

ALTER TABLE series ADD CONSTRAINT series_season_positive CHECK (season IS NULL OR season > 0);

COMMENT ON COLUMN series.season IS 'Номер сезона; пусто, если сезон не задан (например, у фильма)';
