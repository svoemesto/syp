-- Сезон эпизода.
--
-- Фильм — это произведение: у «Игры престолов» десятки эпизодов в нескольких
-- сезонах, у фильма — один эпизод или несколько, и сезона у них нет. Поэтому
-- поле необязательное: пустое значение означает «сезон не задан», а не
-- «сезон забыли внести».
--
-- Порядковый номер эпизода при этом остаётся сквозным по всему фильму: он
-- задаёт последовательность, по которой сценарий собирает эпизод в целом.
ALTER TABLE series ADD COLUMN season integer NULL;

ALTER TABLE series ADD CONSTRAINT series_season_positive CHECK (season IS NULL OR season > 0);

COMMENT ON COLUMN series.season IS 'Номер сезона; пусто, если сезон не задан (например, у фильма)';
