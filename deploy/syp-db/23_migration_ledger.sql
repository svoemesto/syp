-- Учёт применённых миграций.
--
-- Зачем: команда `do.sh db_migrate` переигрывала все файлы с первого, и после
-- любого переименования падала на самом начале — миграция 01 обращается к
-- таблице, которую позже переименовали. Из-за этого переименование схемы
-- превращалось в лотерею: непонятно, что уже применено, и приходилось
-- пересоздавать функции вручную, потому что переименование колонки в их тела
-- не попадает.
--
-- Учёт решает это: применённый файл помечается, повторно не выполняется, а
-- изменение уже применённого файла замечается по сумме.
--
-- Сама таблица учёта не помечает себя: иначе её нечем было бы создать.
CREATE TABLE IF NOT EXISTS tbl_migration_ledger (
    id          BIGSERIAL PRIMARY KEY,
    name        TEXT    NOT NULL UNIQUE,
    checksum    TEXT    NOT NULL,
    applied_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE tbl_migration_ledger IS
    'Применённые миграции: имя файла и сумма содержимого на момент применения';
