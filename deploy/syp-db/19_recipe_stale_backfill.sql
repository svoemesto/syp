-- 19_recipe_stale_backfill.sql — SYP, PostgreSQL 16
--
-- Признак устаревания сценария в таблице с переименованным именем.
--
-- Зачем: миграция 14 добавляла признак устаревания в таблицу сценариев
-- сборки под её прежним именем. На стенде миграции применялись не по
-- порядку: 14 пропущена, а 16 — с переименованием таблицы — применена.
-- Из-за этого признака не оказалось в переименованной таблице, и выпуск
-- сценария падал с «column is_stale does not exist» — то есть на стенде
-- нельзя было выпустить ни одного сценария.
--
-- Что здесь: миграция 14 применена в записи уже нельзя — таблицы с
-- прежним именем больше нет, а правило миграций запрещает их
-- переписывать. Поэтому эффект 14 доводится отдельной миграцией с
-- новым номером.
--
-- Повторное применение безвредно: добавление отсутствующего столбца не
-- меняет уже проставленные значения.

ALTER TABLE tbl_build_recipes
    ADD COLUMN IF NOT EXISTS is_stale BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN tbl_build_recipes.is_stale IS
    'Сценарий устарел: версия схемы фильма разошлась с версией, которой сценарий собран';
