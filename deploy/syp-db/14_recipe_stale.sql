-- 14_recipe_stale.sql — SYP, PostgreSQL 16
--
-- Признак устаревания сценария сборки при смене версии формата.
--
-- Зачем: результат обязан зависеть от версии алгоритма и параметров, а смена
-- версии обязана помечать старые результаты как устаревшие (FR-090). Версия
-- формата хранится в сценарии (`build_recipe.schema_version`) и в настройках
-- фильма (`analysis_setting.recipe.schema_version`), но признака, по
-- которому видно расхождение, не было.
--
-- Решение владельца 2026-10-03 (ADR-0014): сценарий выдаёт и подписывает
-- админский бэкенд, поэтому пометку устаревания ставит он же — при выдаче.
-- Публичная часть только читает признак.
--
-- Пометка ничего не удаляет: сценарий, его файл, подпись и идентификатор ключа
-- остаются на месте, и ранее выданный сценарий остаётся проверяемым по своему
-- ключу, пока он в списке доверенных (ADR-0014, FR-090).
--
-- Миграция добавочная, применяется один раз после 13_season_entity.sql.
-- Ранее применённые миграции не переписываются (constitution III).
--
-- Спецификация: FR-090.
-- Модель: specs/001-first-vertical-slice/data-model.md, раздел 2.20.

ALTER TABLE build_recipe
    ADD COLUMN is_stale BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN build_recipe.is_stale IS
    'Истина, если сценарий создан при другой версии формата, чем действует
     сейчас. Ничего не удаляет: файл, подпись и идентификатор ключа остаются,
     и ранее выданный сценарий остаётся проверяемым по своему ключу (FR-090,
     ADR-0014).';

-- Выборка идёт по фильму и по времени выдачи; без частичного индекса по
-- признаку устаревания фильтр «выдать только актуальные» сканировал бы всю
-- историю сценариев фильма.
CREATE INDEX build_recipe_stale_idx
    ON build_recipe (serial_id, is_stale, created_at DESC);
