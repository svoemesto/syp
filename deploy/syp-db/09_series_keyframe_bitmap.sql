-- 09_series_keyframe_bitmap.sql — SYP, PostgreSQL 16
--
-- Карта ключевых кадров эпизода: длина обязана соответствовать числу кадров.
--
-- Спецификация: FR-023, FR-082, FR-089a.
-- ADR-0001: номер кадра — единственный источник правды.
-- research.md Т-04: признак «кадр ключевой» хранится упакованной битовой
-- картой, один бит на кадр.
-- Модель: specs/001-first-vertical-slice/data-model.md, раздел 2.3.
--
-- Миграция добавочная, применяется один раз после 08_recordhash.sql.
--
-- Зачем ограничение. Длина карты выводится из числа кадров: ceil(кадров / 8)
-- байт. Пока этого правила в базе не было, карта могла быть записана
-- произвольной длины — короче (тогда часть кадров молча считалась
-- неключевыми и воркер резал бы по несуществующим границам) или длиннее
-- (тогда сценарий и воркер считали бы по ней не те кадры). Обе ошибки
-- проявились бы не при регистрации эпизода, а у пользователя, через час работы
-- на своей машине, и выглядели бы как «сценарий не тот».
--
-- Обратная совместимость: карта, уже записанная, этому правилу отвечает —
-- карту пишет только опрос эпизода и только длиной ceil(кадров / 8). Если
-- ограничение всё же отклонит вставку, это расхождение данных, и отказ
-- правильный: молча обрезать карту нельзя, это изменило бы границы.

ALTER TABLE series
    ADD CONSTRAINT series_keyframe_bitmap_length CHECK (
        keyframe_bitmap IS NULL
        OR octet_length(keyframe_bitmap) = (frame_count + 7) / 8
    );

COMMENT ON CONSTRAINT series_keyframe_bitmap_length ON series IS
    'Длина карты ключевых кадров обязана быть ровно ceil(frame_count / 8) байт:
     один бит на кадр, бит 1 — кадр ключевой. Карта короче означала бы, что
     часть кадров молча считается неключевой, длиннее — что границы фрагментов
     считаются по не тем кадрам (FR-082, research.md Т-04).';
