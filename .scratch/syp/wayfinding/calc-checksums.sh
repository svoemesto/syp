#!/bin/bash
# Расчёт эталона sha256 исходников сериала GOT.
# Назначение: воркер на машине пользователя сверяет эти суммы ДО нарезки
# (FR-089), поэтому эталон должен быть полным и точным.
#
# Правила, которые этот скрипт соблюдает:
#   Р-10: запись атомарная — считаем во временный файл, результат
#          переименовываем только после проверки числа строк;
#   Р-10: код возврата проверяется явно, ошибка не остаётся незамеченной;
#   пути в эталоне относительные от корня сериала — структура каталогов
#   у пользователя повторяет машину администратора (FR-089a).

set -euo pipefail

ROOT="/disks/HDD_16Tb_Clouds/GOT"
OUT="/home/nsa/syp/.scratch/syp/wayfinding/GOT.sha256"
TMP="${OUT}.tmp"
EXPECTED=73

echo "[$(date +%T)] старт: корень ${ROOT}"
cd "${ROOT}"

# Сортировка по C locale: иначе порядок зависит от локали и эталон
# невоспроизводим на другой машине.
find . -type f -name '*.mkv' -print0 \
  | LC_ALL=C sort -z \
  | xargs -0 -r sha256sum > "${TMP}"

rc=$?
if [ "${rc}" -ne 0 ]; then
  echo "[$(date +%T)] ОШИБКА: sha256sum вернул код ${rc}"
  rm -f "${TMP}"
  exit "${rc}"
fi

lines=$(wc -l < "${TMP}")
if [ "${lines}" -ne "${EXPECTED}" ]; then
  echo "[$(date +%T)] ОШИБКА: ожидалось ${EXPECTED} файлов, получено ${lines}"
  echo "Неполный эталон хуже отсутствующего: он молча отвергнет
      корректные файлы пользователя. Временный файл оставлен для разбора: ${TMP}"
  exit 1
fi

mv "${TMP}" "${OUT}"
echo "[$(date +%T)] ГОТОВО: ${lines} файлов, эталон записан в ${OUT}"
sha256sum "${OUT}"
